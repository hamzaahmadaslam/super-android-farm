#!/usr/bin/env python3
"""Generate docs/CLI.md from the real argparse parser of `sf`.

    python scripts/gen_cli_docs.py                        print the reference
    python scripts/gen_cli_docs.py -o docs/CLI.md         write it
    python scripts/gen_cli_docs.py --check docs/CLI.md    exit 1 when the file is not current

The text is built only from the parser (names, summaries, usage, options, defaults and the
example every command carries), so a command, option or example cannot exist without
appearing in the reference. Nothing in the output depends on the machine or the date.
"""
from __future__ import annotations

import argparse
import os
import re
import sys
from pathlib import Path

# argparse wraps usage lines to the terminal width. Pin it so the output is the same everywhere.
os.environ["COLUMNS"] = "100"
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from superfarm.cli.main import build_parser  # noqa: E402

HEADER = """\
# Command reference

<!-- Generated by scripts/gen_cli_docs.py from the parser of `sf`. Do not edit by hand:
     change the command's definition in superfarm/cli/ and run
     `python scripts/gen_cli_docs.py -o docs/CLI.md`. -->

For anyone who runs the farm from a terminal or a script. Every command of `sf`, with its usage,
options and an example. `sf <command> --help` prints the same text for one command.

## Conventions

`sf` has two kinds of commands. Local commands (`doctor`, `host`, `config`, `token`, `serve`,
`service`, `version`, `completion`) work on the machine and need no daemon. All others talk to
the daemon over HTTP, so the daemon must be running (`sf serve` or `sf service start`).

A selector picks Androids. It is one of `all`, `running`, `stopped`, `tag:NAME`, a number such
as `5`, or a range such as `1-10`. Join selectors with commas and exclude with `!`, for example
`1-10,tag:eu,!tag:spare`.

Exit codes: 0 success, 1 the operation failed, 2 wrong usage, 130 interrupted with Ctrl-C. `sf doctor` exits 1 when a check fails, and `sf service status` exits 3 when the service is not active.

The global options below are accepted before and after the command name (`sf --json ls` and
`sf ls --json` are the same).
"""

FOOTER = """\
## Next

- [Quickstart](QUICKSTART.md) shows the common commands in order.
- [API reference](API.md) lists the routes behind the client commands.
- [Configuration reference](CONFIGURATION.md) lists every setting that `sf config` and `sf set` accept.
- [Troubleshooting](TROUBLESHOOTING.md) covers what to do when a command fails.
"""


def _is_global(parser: argparse.ArgumentParser, action: argparse.Action) -> bool:
    for group in parser._action_groups:
        if group.title == "global options" and action in group._group_actions:
            return True
    return False


def _subparsers(parser: argparse.ArgumentParser) -> argparse._SubParsersAction | None:
    for action in parser._actions:
        if isinstance(action, argparse._SubParsersAction):
            return action
    return None


def _children(action: argparse._SubParsersAction) -> list[tuple[str, list[str], argparse.ArgumentParser, str]]:
    """(name, aliases, parser, summary) in the order the commands were added."""
    seen: dict[int, tuple[str, list[str], argparse.ArgumentParser, str]] = {}
    summaries = {c.dest: c.help or "" for c in action._choices_actions}
    for name, child in action.choices.items():
        key = id(child)
        if key in seen:
            seen[key][1].append(name)
        else:
            seen[key] = (name, [], child, summaries.get(name, ""))
    return list(seen.values())


def _own_actions(parser: argparse.ArgumentParser) -> list[argparse.Action]:
    return [a for a in parser._actions
            if not isinstance(a, (argparse._HelpAction, argparse._SubParsersAction)) and not _is_global(parser, a)]


def _usage(parser: argparse.ArgumentParser) -> str:
    own = _own_actions(parser)
    formatter = parser._get_formatter()
    groups = [g for g in parser._mutually_exclusive_groups if all(a in own for a in g._group_actions)]
    formatter.add_usage(None, own, groups, prefix="")
    return formatter.format_help().strip()


def _cell(text: str) -> str:
    return " ".join(str(text).split()).replace("|", "\\|")


def _default(action: argparse.Action) -> str:
    default = action.default
    if default in (None, argparse.SUPPRESS, False) or isinstance(action, argparse._StoreTrueAction):
        return ""
    if isinstance(default, (list, tuple)) and not default:
        return ""
    return f"`{default}`"


def _help_text(action: argparse.Action) -> str:
    text = _cell(action.help or "")
    return text.replace("%(default)s", str(action.default))


def _positionals(parser: argparse.ArgumentParser) -> list[argparse.Action]:
    return [a for a in _own_actions(parser) if not a.option_strings]


def _optionals(parser: argparse.ArgumentParser) -> list[argparse.Action]:
    return [a for a in _own_actions(parser) if a.option_strings]


def _arg_name(action: argparse.Action) -> str:
    if action.choices:
        return "{" + ",".join(str(c) for c in action.choices) + "}"
    return action.metavar or action.dest


def _option_flags(action: argparse.Action) -> str:
    flags = ", ".join(action.option_strings)
    if action.nargs == 0 or isinstance(action, (argparse._StoreTrueAction, argparse._StoreFalseAction,
                                                argparse.BooleanOptionalAction)):
        return f"`{flags}`"
    value = action.metavar or action.dest.upper()
    if action.choices:
        value = "{" + ",".join(str(c) for c in action.choices) + "}"
    return f"`{flags} {value}`"


def _example(parser: argparse.ArgumentParser) -> str:
    epilog = parser.epilog or ""
    if not epilog.startswith("example:"):
        return ""
    lines = epilog.splitlines()[1:]
    return "\n".join(line[2:] if line.startswith("  ") else line for line in lines)


def _section(parser: argparse.ArgumentParser, depth: int, summary: str, aliases: list[str], out: list[str]) -> None:
    title = parser.prog
    out += ["", f"{'#' * depth} {title}", ""]
    if aliases:
        parent = parser.prog.rsplit(" ", 1)[0]
        names = ", ".join("`" + parent + " " + a + "`" for a in aliases)
        out += [f"Alias: {names}.", ""]
    description = (parser.description or summary).strip()
    out += [description, ""]
    sub = _subparsers(parser)
    if sub is None:
        out += ["```", _usage(parser), "```", ""]
        positionals = _positionals(parser)
        if positionals:
            out += ["| Argument | Description |", "| --- | --- |"]
            out += [f"| `{_arg_name(a)}` | {_help_text(a)} |" for a in positionals]
            out += [""]
        optionals = _optionals(parser)
        if optionals:
            out += ["| Option | Default | Description |", "| --- | --- | --- |"]
            out += [f"| {_option_flags(a)} | {_default(a)} | {_help_text(a)} |" for a in optionals]
            out += [""]
        example = _example(parser)
        if example:
            out += ["Example:", "", "```", example, "```", ""]
        return
    children = _children(sub)
    out += ["| Command | What it does |", "| --- | --- |"]
    out += [f"| `{parser.prog} {name}` | {_cell(text)} |" for name, _aliases, _child, text in children]
    out += [""]
    for _name, child_aliases, child, text in children:
        _section(child, min(depth + 1, 4), text, child_aliases, out)


def render() -> str:
    parser = build_parser()
    sub = _subparsers(parser)
    assert sub is not None
    out = [HEADER.rstrip("\n"), ""]
    glob = [a for a in parser._actions if _is_global(parser, a)]
    out += ["| Option | Description |", "| --- | --- |"]
    out += [f"| {_option_flags(a)} | {_help_text(a)} |" for a in glob]
    out += ["", "## Commands", "", "| Command | What it does |", "| --- | --- |"]
    for name, aliases, _child, text in _children(sub):
        label = f"`sf {name}`" + (f" (`{'`, `'.join(aliases)}`)" if aliases else "")
        out += [f"| {label} | {_cell(text)} |"]
    for _name, aliases, child, text in _children(sub):
        _section(child, 2, text, aliases, out)
    out += ["", FOOTER.rstrip("\n"), ""]
    return re.sub(r"\n{3,}", "\n\n", "\n".join(out))


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Generate docs/CLI.md from the sf parser.")
    ap.add_argument("-o", "--output", metavar="FILE", help="write to FILE instead of printing")
    ap.add_argument("--check", metavar="FILE", help="exit 1 when FILE differs from what would be generated")
    args = ap.parse_args(argv)
    text = render()
    if args.check:
        path = Path(args.check)
        if not path.is_file() or path.read_text(encoding="utf-8") != text:
            print(f"{args.check} is out of date: run  python scripts/gen_cli_docs.py -o {args.check}", file=sys.stderr)
            return 1
        return 0
    if args.output:
        Path(args.output).write_text(text, encoding="utf-8")
        return 0
    sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
