#!/usr/bin/env python3
"""Generate the route reference of docs/API.md from the app's own OpenAPI schema.

    python scripts/gen_api_docs.py                      print the reference
    python scripts/gen_api_docs.py -o docs/API.md       write docs/API.md (hand-written part + reference)
    python scripts/gen_api_docs.py --check docs/API.md  exit 1 when the file is not current

docs/API.md has two parts. Everything above the marker line (authentication, errors, tasks,
WebSockets) is written by hand and kept as it is; the route reference below the marker is
generated from `create_app(...).openapi()`, built with a throwaway home so nothing of a real
farm is touched.
"""
from __future__ import annotations

import argparse
import re
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

MARKER = "<!-- The route reference below is generated by scripts/gen_api_docs.py. Do not edit it by hand. -->"
METHODS = ("get", "post", "put", "patch", "delete")


def _schema(spec: dict, node: dict) -> dict:
    ref = node.get("$ref")
    return spec["components"]["schemas"][ref.rsplit("/", 1)[-1]] if ref else node


def _type(spec: dict, node: dict) -> str:
    if "$ref" in node:
        target = _schema(spec, node)
        if target.get("enum"):
            return " or ".join(f"`{v}`" for v in target["enum"])
        return target.get("title", node["$ref"].rsplit("/", 1)[-1])
    if "enum" in node:
        return " or ".join(f"`{v}`" for v in node["enum"])
    if "const" in node:
        return f"`{node['const']}`"
    for key in ("anyOf", "oneOf"):
        if key in node:
            parts = [_type(spec, n) for n in node[key] if n.get("type") != "null"]
            nullable = any(n.get("type") == "null" for n in node[key])
            text = " or ".join(dict.fromkeys(parts)) or "any"
            return text + (" (may be null)" if nullable else "")
    kind = node.get("type")
    if kind == "array":
        return f"list of {_type(spec, node.get('items') or {})}"
    if kind == "object":
        extra = node.get("additionalProperties")
        return f"map of text to {_type(spec, extra)}" if isinstance(extra, dict) and extra else "object"
    names = {"string": "text", "integer": "whole number", "number": "number", "boolean": "true / false"}
    return names.get(str(kind), str(kind or "any"))


def _limits(node: dict) -> str:
    node = {k: (int(v) if isinstance(v, float) and v.is_integer() else v) for k, v in node.items()}
    bits = []
    for key, label in (("minimum", "at least"), ("exclusiveMinimum", "more than"), ("maximum", "at most"),
                       ("exclusiveMaximum", "less than"), ("minLength", "length at least"),
                       ("maxLength", "length at most"), ("maxItems", "at most items")):
        if key in node:
            bits.append(f"{label} {node[key]}")
    if "pattern" in node:
        bits.append(f"matches `{node['pattern']}`")
    return ", ".join(bits)


def _cell(text: object) -> str:
    return " ".join(str(text).split()).replace("|", "\\|")


def _fields(spec: dict, model: dict) -> list[tuple[str, str, str]]:
    """(name, type, notes) for the properties of a request body."""
    model = _schema(spec, model)
    required = set(model.get("required", []))
    rows = []
    for name, raw in model.get("properties", {}).items():
        node = _schema(spec, raw) if "$ref" in raw and not _schema(spec, raw).get("enum") else raw
        notes = []
        notes.append("required" if name in required else "optional")
        if "default" in raw:
            notes.append(f"default `{raw['default']!r}`".replace("'", '"') if isinstance(raw["default"], str)
                         else f"default `{raw['default']}`")
        limits = _limits(raw)
        if limits:
            notes.append(limits)
        if raw.get("description"):
            notes.append(" ".join(str(raw["description"]).split()))
        rows.append((name, _type(spec, raw) if node is raw else _type(spec, raw), "; ".join(notes)))
    return rows


def _body_model(spec: dict, op: dict) -> dict | None:
    body = op.get("requestBody")
    if not body:
        return None
    content = body.get("content", {})
    for media in ("application/json", "multipart/form-data"):
        if media in content:
            return {"media": media, "schema": content[media].get("schema", {})}
    return None


def _first_paragraph(text: str) -> str:
    return " ".join(text.strip().split("\n\n")[0].split()) if text else ""


def collect() -> tuple[dict, list[tuple[str, str]], set[str]]:
    from fastapi.routing import APIRoute

    from superfarm.api import ws
    from superfarm.api.app import create_app
    from superfarm.api.routes import system
    from superfarm.farm import Farm

    with tempfile.TemporaryDirectory(prefix="sf-api-docs-") as home:
        farm = Farm(home)
        try:
            app = create_app(farm)
            spec = app.openapi()
            sockets = sorted((r.path, "WebSocket") for r in ws.router.routes if not isinstance(r, APIRoute))
        finally:
            farm.close()
    public = {(m, r.path) for r in system.public.routes for m in getattr(r, "methods", set())}
    return spec, sockets, {f"{m} {p}" for m, p in public}


def render_reference() -> str:
    spec, sockets, public = collect()
    groups: dict[str, list[tuple[str, str, dict]]] = {}
    for path, ops in spec["paths"].items():
        parts = path.strip("/").split("/")
        group = "/".join(parts[:2]) if len(parts) > 1 else path
        for method in METHODS:
            if method in ops:
                groups.setdefault(group, []).append((method.upper(), path, ops[method]))
    out = ["## Route reference", "",
           "Generated from the application's OpenAPI schema. Every route needs authentication except the ones marked "
           "public. `Body` lists the JSON fields of the request; a field marked required must be present, and "
           "fields the route does not list are refused with `422`. Routes that start work return `202` with a "
           "task (see [Tasks](#tasks)).", ""]
    count = sum(len(v) for v in groups.values())
    out += [f"The API has {count} routes under {len(groups)} prefixes and {len(sockets)} WebSocket routes.", ""]
    out += ["| Prefix | Routes |", "| --- | --- |"]
    for group, routes in groups.items():
        out.append(f"| [`{group}`](#{re.sub(r'[^a-z0-9 -]', '', group.lower()).replace(' ', '-')}) | {len(routes)} |")
    out.append("")
    for group, routes in groups.items():
        out += [f"### {group}", ""]
        for method, path, op in routes:
            out += [f"#### {method} {path}", ""]
            summary = op.get("summary", "")
            description = _first_paragraph(op.get("description", ""))
            line = description or summary
            if f"{method} {path}" in public:
                line += " Public: no authentication."
            out += [line, ""]
            params = [p for p in op.get("parameters", [])]
            if params:
                out += ["| Parameter | In | Type | Notes |", "| --- | --- | --- | --- |"]
                for p in params:
                    node = p.get("schema", {})
                    notes = ["required" if p.get("required") else "optional"]
                    if "default" in node:
                        notes.append(f"default `{node['default']}`")
                    limits = _limits(node)
                    if limits:
                        notes.append(limits)
                    if p.get("description"):
                        notes.append(_cell(p["description"]))
                    out.append(f"| `{p['name']}` | {p['in']} | {_type(spec, node)} | {'; '.join(notes)} |")
                out.append("")
            body = _body_model(spec, op)
            if body:
                rows = _fields(spec, body["schema"])
                label = "Body (multipart form)" if body["media"] == "multipart/form-data" else "Body"
                if rows:
                    out += [f"{label}:", "", "| Field | Type | Notes |", "| --- | --- | --- |"]
                    out += [f"| `{n}` | {t} | {_cell(x)} |" for n, t, x in rows]
                    out.append("")
                else:
                    out += [f"{label}: see the route's description.", ""]
    if sockets:
        out += ["### WebSocket routes", "", "| Path | Notes |", "| --- | --- |"]
        for path, _kind in sockets:
            out.append(f"| `{path}` | See [WebSockets](#websockets). |")
        out.append("")
    out += ["## Next", "",
            "- [Command reference](CLI.md) shows the `sf` command for most of these routes.",
            "- [Security model](SECURITY_MODEL.md) explains what the API token allows.",
            "- [MCP server](MCP.md) and [AI assistants](AI.md) use this API on behalf of an assistant.",
            "- [Configuration reference](CONFIGURATION.md) lists the settings that `PATCH /api/config` changes.", ""]
    return "\n".join(out)


def render(existing: str) -> str:
    """The file with its hand-written head kept and its generated tail replaced."""
    if MARKER not in existing:
        raise SystemExit(f"the marker line is missing from the file; add this line where the reference should start:\n{MARKER}")
    head = existing.split(MARKER, 1)[0].rstrip("\n")
    return re.sub(r"\n{3,}", "\n\n", f"{head}\n\n{MARKER}\n\n{render_reference()}\n")


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Generate docs/API.md (hand-written head + generated routes).")
    ap.add_argument("file", nargs="?", default=str(ROOT / "docs" / "API.md"), help="the file to read the hand-written head from")
    ap.add_argument("-o", "--output", metavar="FILE", help="write to FILE instead of printing")
    ap.add_argument("--check", metavar="FILE", help="exit 1 when FILE differs from what would be generated")
    args = ap.parse_args(argv)
    source = Path(args.check or args.output or args.file)
    text = render(source.read_text(encoding="utf-8"))
    if args.check:
        path = Path(args.check)
        if text != path.read_text(encoding="utf-8"):
            print(f"{args.check} is out of date: run  python scripts/gen_api_docs.py -o {args.check}", file=sys.stderr)
            return 1
        return 0
    if args.output:
        Path(args.output).write_text(text, encoding="utf-8")
        return 0
    sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
