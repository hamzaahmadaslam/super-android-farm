"""`sf config docs`: the settings reference, generated from the settings themselves.

docs/CONFIGURATION.md is rendered from the Config model tree, so a setting cannot exist
without appearing in the reference and the reference cannot describe one that is gone.
The output depends only on the models (no dates, no host facts, no ordering by hash), so
CI can regenerate it and fail when the committed file differs.
"""
from __future__ import annotations

import json
import re
from typing import Any, get_args

from pydantic import BaseModel

from ..config import Config

HEADER = """\
# Configuration reference

<!-- Generated by `sf config docs` from superfarm/config.py. Do not edit by hand:
     change the setting's definition and run `sf config docs -o docs/CONFIGURATION.md`. -->

Every setting of a farm, with its default. Settings live in `config.yaml` in the farm home
(`sf config path` prints where); the file holds only what differs from the defaults below.

    sf config show                    the settings in effect
    sf config get android.fps         one value
    sf config set android.fps 25      change one value (validated before it is saved)
    sf config unset android.fps       back to the default

Keys are written with dots: `network.vpn.selection` is `selection` under `vpn` under
`network`. Farm-wide values are defaults; most can be overridden for a single Android with
`sf set <selector> key=value`.
"""

COLUMNS = ("Key", "Type", "Default", "Allowed", "Description")
ENTRY = "<name>"


def _resolve(schema: dict, node: dict) -> dict:
    """Follow a `$ref` into the schema's definitions."""
    ref = node.get("$ref")
    if not ref:
        return node
    return schema["$defs"][ref.rsplit("/", 1)[-1]]


def _is_group(schema: dict, node: dict) -> bool:
    return "properties" in _resolve(schema, node)


def _entry_model(schema: dict, node: dict) -> dict | None:
    """The model of a `name -> settings` mapping (android.images, network.gateways), else None."""
    extra = node.get("additionalProperties")
    if node.get("type") == "object" and isinstance(extra, dict) and _is_group(schema, extra):
        return _resolve(schema, extra)
    return None


def _type(node: dict) -> str:
    kind = node.get("type")
    if "enum" in node:
        return "choice"
    if kind == "array":
        return f"list of {_type(node.get('items') or {})}"
    if kind == "object":
        extra = node.get("additionalProperties")
        return f"map of text to {_type(extra)}" if isinstance(extra, dict) else "map"
    return {"string": "text", "integer": "whole number", "number": "number", "boolean": "true / false"}.get(
        str(kind), str(kind or "any"))


def _number(value: Any) -> str:
    return str(int(value)) if isinstance(value, float) and value.is_integer() else str(value)


def _allowed(node: dict) -> str:
    """Constraints in words: choices, numeric range, length, pattern."""
    parts: list[str] = []
    if "enum" in node:
        parts.append(", ".join(f"`{v}`" for v in node["enum"]))
    low = ("at least " + _number(node["minimum"]) if "minimum" in node
           else "more than " + _number(node["exclusiveMinimum"]) if "exclusiveMinimum" in node else "")
    high = ("at most " + _number(node["maximum"]) if "maximum" in node
            else "less than " + _number(node["exclusiveMaximum"]) if "exclusiveMaximum" in node else "")
    if "minimum" in node and "maximum" in node:
        parts.append(f"{_number(node['minimum'])} to {_number(node['maximum'])}")
    elif low or high:
        parts.append(", ".join(p for p in (low, high) if p))
    if "maxLength" in node:
        parts.append(f"up to {node['maxLength']} characters")
    if "pattern" in node:
        parts.append(f"matches `{node['pattern']}`")
    return "; ".join(parts)


def _default(value: Any) -> str:
    return f"`{json.dumps(value, ensure_ascii=False, sort_keys=True)}`"


def _escape(text: str) -> str:
    """Make free text safe for a Markdown table cell. `<home>` outside a code span would be
    swallowed as an HTML tag, and a bare `|` would end the cell (also inside a code span)."""
    pieces = re.split(r"(`[^`]*`)", " ".join(text.split()))
    out = [p if p.startswith("`") else p.replace("<", "\\<").replace(">", "\\>") for p in pieces]
    return "".join(out).replace("|", "\\|")


def _table(rows: list[tuple[str, ...]]) -> list[str]:
    lines = ["| " + " | ".join(COLUMNS) + " |", "|" + "|".join(" --- " for _ in COLUMNS) + "|"]
    lines += ["| " + " | ".join(_escape(c) for c in row) + " |" for row in rows]
    return lines


_MISSING = object()


def _lookup(defaults: Any, path: list[str]) -> Any:
    node = defaults
    for part in path:
        if not isinstance(node, dict) or part not in node:
            return _MISSING
        node = node[part]
    return node


def _section(schema: dict, group: dict, path: list[str], defaults: Any, out: list[str], *,
             title: str | None = None, intro: str = "") -> None:
    """One heading + table for the plain settings of `group`, then its nested groups."""
    rows: list[tuple[str, ...]] = []
    nested: list[tuple[str, dict, dict]] = []
    required = set(group.get("required") or [])
    for name, raw in group.get("properties", {}).items():
        node = _resolve(schema, raw)
        if _is_group(schema, raw):
            nested.append((name, node, raw))
            continue
        key = ".".join([*path, name])
        entries = _entry_model(schema, node)
        if entries is not None:
            nested.append((name, node, raw))
            rows.append((f"`{key}`", "map of name to settings", f"see `{key}.{ENTRY}`", "",
                         node.get("description", "")))
            continue
        value = _lookup(defaults, [*path, name])
        if value is _MISSING:
            value = node.get("default", _MISSING)
        default = "required" if name in required and value is _MISSING else "" if value is _MISSING else _default(value)
        rows.append((f"`{key}`", _type(node), default, _allowed(node), node.get("description", "")))
    if rows or intro or len(path) == 1:
        # A top-level group always gets its heading, even when all it holds is sub-groups.
        depth = "##" if len(path) <= 1 else "###"
        out += ["", f"{depth} {_escape(title or '.'.join(path))}"]
        if intro:
            out += ["", intro]
        if rows:
            out += ["", *_table(rows)]
    for name, node, _raw in nested:
        entries = _entry_model(schema, node)
        if entries is None:
            _section(schema, node, [*path, name], defaults, out)
            continue
        key = ".".join([*path, name])
        present = _lookup(defaults, [*path, name])
        names = list(present) if isinstance(present, dict) else []
        intro = (f"One group per entry of `{key}`; `{ENTRY}` is the entry's name. "
                 + (f"Entries present by default: {', '.join(f'`{n}`' for n in names)}." if names
                    else "No entries by default."))
        # Entry fields take their defaults from the entry model, not from one entry's values.
        _section(schema, entries, [*path, name, ENTRY], None, out, intro=intro)


def render(model: type[BaseModel] = Config) -> str:
    """The whole reference as Markdown."""
    schema = model.model_json_schema()
    defaults = model().model_dump(mode="json")
    out = [HEADER.rstrip("\n")]
    general = {"properties": {k: v for k, v in schema["properties"].items() if not _is_group(schema, v)},
               "required": schema.get("required", [])}
    _section(schema, general, [], defaults, out, title="General")
    for name, raw in schema["properties"].items():
        if _is_group(schema, raw):
            _section(schema, _resolve(schema, raw), [name], defaults, out)
    return "\n".join(out) + "\n"


def undocumented(model: type[BaseModel] = Config, prefix: str = "") -> list[str]:
    """Settings without a description (nested groups themselves need none)."""
    missing: list[str] = []
    for name, field in model.model_fields.items():
        annotation = field.annotation
        if isinstance(annotation, type) and issubclass(annotation, BaseModel):
            missing += undocumented(annotation, f"{prefix}{name}.")
            continue
        if not (field.description or "").strip():
            missing.append(f"{prefix}{name}")
        for inner in get_args(annotation):
            if isinstance(inner, type) and issubclass(inner, BaseModel):
                missing += undocumented(inner, f"{prefix}{name}.{ENTRY}.")
    return missing
