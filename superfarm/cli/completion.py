"""`sf completion bash|zsh`: a static completion script generated from the parser.

Static on purpose: the script completes commands and options without starting Python on
every Tab press, and without talking to the daemon. It is rebuilt from the same parser the
CLI runs, so it cannot list a command that does not exist.

zsh gets the same function through its bash-compatibility layer (bashcompinit), which is
how zsh itself recommends reusing a bash completion.
"""
from __future__ import annotations

import argparse
import re

from .common import EXIT_OK, Ctx

_SAFE_WORD = re.compile(r"^[A-Za-z0-9][A-Za-z0-9_.:+-]*$|^--?[A-Za-z0-9][A-Za-z0-9-]*$")


def tree(parser: argparse.ArgumentParser, path: tuple[str, ...] = ()) -> dict[tuple[str, ...], list[str]]:
    """command path -> words that may follow it (sub-commands first, then options)."""
    commands: list[str] = []
    options: list[str] = []
    children: dict[str, argparse.ArgumentParser] = {}
    for action in parser._actions:      # noqa: SLF001 - argparse has no public way to walk a parser
        if isinstance(action, argparse._SubParsersAction):   # noqa: SLF001
            for name, child in action.choices.items():
                commands.append(name)
                children[name] = child
        else:
            options += [o for o in action.option_strings if o.startswith("--")]
            if action.choices and not action.option_strings:
                commands += [str(c) for c in action.choices]
    out = {path: [*commands, *sorted(set(options))]}
    for name, child in children.items():
        out.update(tree(child, (*path, name)))
    return out


def _check(words: list[str]) -> list[str]:
    for word in words:
        # Everything here comes from our own parser; this keeps it that way if someone
        # later adds a command name that would need quoting inside the script.
        if not _SAFE_WORD.match(word):
            raise ValueError(f"word cannot be used in a completion script: {word!r}")
    return words


def bash(parser: argparse.ArgumentParser, prog: str = "sf") -> str:
    table = tree(parser)
    lines = [
        f"# bash completion for {prog}. Generated by `{prog} completion bash`; do not edit.",
        f"_{prog}_complete() {{",
        '    local cur="${COMP_WORDS[COMP_CWORD]}" path="" words="" i word',
        "    for ((i = 1; i < COMP_CWORD; i++)); do",
        '        word="${COMP_WORDS[i]}"',
        '        case "$word" in -*) continue ;; esac',
        '        case "$path/$word" in',
    ]
    paths = ["/" + "/".join(_check(list(p))) for p in table if p]
    lines += [f"            {'|'.join(paths)}) path=\"$path/$word\" ;;", "        esac", "    done", '    case "$path" in']
    for path, words in table.items():
        key = "/" + "/".join(path) if path else ""
        lines.append(f"        \"{key}\") words=\"{' '.join(_check(words))}\" ;;")
    lines += [
        "    esac",
        '    COMPREPLY=($(compgen -W "$words" -- "$cur"))',
        "}",
        # -o default: when nothing matches (a file argument), fall back to file names.
        f"complete -o default -F _{prog}_complete {prog}",
        "",
    ]
    return "\n".join(lines)


def zsh(parser: argparse.ArgumentParser, prog: str = "sf") -> str:
    body = bash(parser, prog).splitlines()
    return "\n".join([
        f"#compdef {prog}",
        f"# zsh completion for {prog}. Generated by `{prog} completion zsh`; do not edit.",
        "autoload -U +X bashcompinit && bashcompinit",
        *body[1:],
        "",
    ])


def run(ctx: Ctx) -> int:
    from .main import build_parser
    parser = build_parser()
    ctx.out.stdout.write(bash(parser) if ctx.args.shell == "bash" else zsh(parser))
    return EXIT_OK
