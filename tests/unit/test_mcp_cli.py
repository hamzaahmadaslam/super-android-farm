def test_sf_mcp_as_a_subprocess_speaks_the_protocol_on_stdout_and_nothing_else(home, stub):
    """What a desktop assistant does: start the command from the snippet and talk over the pipe."""
    pytest.importorskip("mcp", reason="the optional MCP SDK is not installed")
    import anyio
    import mcp_types as types
    from mcp import Client, StdioServerParameters, stdio_client

    stub.on("GET", "/api/mcp/info", Policy().to_dict())
    stub.on("GET", "/api/instances", {"instances": [instance(1, state="booted", name="shop")]})
    params = StdioServerParameters(command=sys.executable, args=["-m", "superfarm.cli.main", "--home", str(home.home), "mcp"],
                                   env={"SUPERFARM_HOME": str(home.home), "PYTHONPATH": str(REPO)}, cwd=str(home.home))

    async def main():
        # The server's stderr goes to a real file: under pytest, sys.stderr may have no descriptor to inherit.
        with open(home.home / "mcp-stderr.log", "w") as errlog:
            async with Client(stdio_client(params, errlog=errlog), mode="legacy",
                              client_info=types.Implementation(name="Pipe Client", version="1")) as client:
                tools = (await client.list_tools()).tools
                result = await client.call_tool("list_androids", {})
                return client.server_info.name, [t.name for t in tools], result

    name, tools, result = anyio.run(main)
    assert (home.home / "mcp-stderr.log").read_text() == ""       # and it had nothing to complain about
    assert name == "superfarm" and tools == [n for n in TOOL_NAMES if n != "run_shell"]
    assert result.is_error is False and result.structured_content["androids"][0]["name"] == "shop"
    assert {r.headers.get("x-sf-caller") for r in stub.requests if r.method == "GET"} == {"mcp:Pipe_Client"}
    ended = [r.path for r in stub.calls("DELETE")]              # leaving tells the daemon the session is over
    assert len(ended) == 1 and re.fullmatch(r"/api/approvals/sessions/mcp-[0-9a-f]{16}", ended[0])


