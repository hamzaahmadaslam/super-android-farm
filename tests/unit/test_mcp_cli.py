def watch(capsys, monkeypatch, stub, typed: str, rounds: int = 3):
    ticks = []

    def sleep(self, seconds):
        ticks.append(seconds)
        if len(ticks) >= rounds:
            raise KeyboardInterrupt

    monkeypatch.setattr(Ctx, "sleep", sleep)
    monkeypatch.setattr(sys, "stdin", FakeStdin(typed))
    return run_sf(capsys, "approvals", "watch")


def test_watch_asks_yes_or_no_for_each_request_oldest_first(home, stub, capsys, monkeypatch):
    queue = [approval("22220000", summary="Start Android 3", tool="start_androids"), approval("11110000")]

    def listing(request):
        return {"approvals": list(queue), "pending": len(queue), "now": 1001.0}

    stub.on("GET", "/api/approvals", listing)
    stub.on("POST", "/api/approvals/11110000/approve", lambda r: (queue.pop(), {"approval": approval("11110000", "approved")})[1])
    stub.on("POST", "/api/approvals/22220000/deny", lambda r: (queue.pop(), {"approval": approval("22220000", "denied")})[1])
    run = watch(capsys, monkeypatch, stub, "y\nn\nnot now please\n")
    assert run.code == 130
    assert run.err.index("Stop 2 Androids: Android 1, 2") < run.err.index("Start Android 3")
    assert "mcp:desk asks (change):" in run.err and "[y]es / [n]o / [s]kip / yes and [r]emember" in run.err
    assert stub.calls("POST", "/api/approvals/11110000/approve")[0].json == {"via": "terminal", "remember": False}
    assert stub.calls("POST", "/api/approvals/22220000/deny")[0].json == {"via": "terminal", "reason": "not now please"}
    assert stub.calls("GET", "/api/approvals")[0].query == {"state": "pending"}


def test_watch_remember_skip_and_requests_answered_elsewhere(home, stub, capsys, monkeypatch):
    queue = [approval("33330000", klass="destructive", can_remember=False, summary="Delete Android 9 and its data"),
             approval("22220000"), approval("11110000")]
    stub.on("GET", "/api/approvals", lambda request: {"approvals": list(queue), "pending": len(queue), "now": 1.0})
    stub.on("POST", "/api/approvals/11110000/approve", lambda r: (queue.pop(), {"approval": approval("11110000", "approved")})[1])
    stub.on("POST", "/api/approvals/22220000/approve",
            lambda r: (queue.pop(), (409, {"error": {"code": "conflict", "message": "it was already approved by panel"}}))[1])
    run = watch(capsys, monkeypatch, stub, "r\ny\n\n", rounds=2)
    assert stub.calls("POST", "/api/approvals/11110000/approve")[0].json == {"via": "terminal", "remember": True}
    assert "no longer open: it was already approved by panel" in run.err
    # The destructive one offers no "remember", and an empty answer skips it without deciding.
    destructive = run.err[run.err.index("Delete Android 9"):]
    assert "[r]emember" not in destructive.splitlines()[1] and "skipped; it stays in the list" in destructive
    assert not stub.calls("POST", "/api/approvals/33330000/approve") and not stub.calls("POST", "/api/approvals/33330000/deny")


