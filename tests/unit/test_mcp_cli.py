class FakeStdin(io.StringIO):
    def __init__(self, text: str = "", tty: bool = True):
        super().__init__(text)
        self._tty = tty

    def isatty(self) -> bool:
        return self._tty


def approval(approval_id="0a1b2c3d", state="pending", **more):
    return {"id": approval_id, "created": 1000.0, "expires": 1300.0, "caller": "mcp:desk", "session": "s1",
            "tool": "stop_androids", "klass": "change", "summary": "Stop 2 Androids: Android 1, 2",
            "arguments": {"selector": "1-2"}, "targets": [1, 2], "can_remember": True, "state": state,
            "decided_by": "", "decided_at": 0.0, "reason": "", "remembered": False, **more}


