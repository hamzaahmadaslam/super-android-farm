#!/usr/bin/env python3
"""Write the data the demo's fake backend takes from the real code.

    .venv/bin/python demo/scripts/generate.py            write demo/mock/generated/*.js
    .venv/bin/python demo/scripts/generate.py --check    exit 1 when a file is out of date

The demo is built on a service that has Node but not this package's Python environment, so
the files are generated here and committed. `tests/unit/test_demo_contract.py` runs the
check, which keeps them in step with the code they were made from.

Each file is a JavaScript module holding one JSON value (`export default ...`), so that a
browser and Node both load it without a request and without a build step.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "demo" / "mock" / "generated"
HEADER = "// Generated by demo/scripts/generate.py from the code under superfarm/. Do not edit.\n"

# Requests the simulated assistant files on the Approvals page. The line an operator reads
# is written by the real tool from these arguments; 901 and 902 stand for the Androids the
# demo picks when it files the request.
APPROVAL_SAMPLES = [
    ("restart_androids", {"selector": "901"}),
    ("stop_androids", {"selector": "901,902"}),
    ("create_backup", {"selector": "901"}),
    ("type_text", {"selector": "901", "text": "hello from the demo"}),
    ("clear_app_data", {"selector": "901", "package": "example.notes"}),
    ("delete_androids", {"selector": "901"}),
]


# The invented machine the demo's farm runs on. Its capacity estimate is the real
# estimator's answer for this machine, so the numbers on the dashboard are computed, not made up.
HOST = {
    "home": "/home/demo/.local/share/superfarm",
    "host": {"distro": "Example Linux 12 (demo host)", "distro_id": "example", "family": "debian", "kernel": "6.12.0-demo", "arch": "x86_64",
             "cpu": {"model": "Example 16-core processor", "threads": 32}, "ram_mb": 65536, "swap_mb": 16384},
    "gpus": [
        {"node": "/dev/dri/renderD128", "driver": "i915", "vendor": "intel", "name": "Demo integrated graphics", "pci": "0000:00:02.0",
         "usable_modes": ["intel"], "discrete": False, "vram_mb": None, "note": "", "integrated": True},
        {"node": "/dev/dri/renderD129", "driver": "nvidia", "vendor": "nvidia", "name": "Demo discrete graphics card (16 GB)", "pci": "0000:01:00.0",
         "usable_modes": ["nvidia"], "discrete": True, "vram_mb": 16384, "note": "", "integrated": False},
    ],
}
GPU_MODES = ("auto", "software", "igpu", "dgpu", "intel", "amd", "nvidia")


def demo_capacity() -> dict[str, dict]:
    """The real estimate for the invented host, once for each farm-wide rendering mode."""
    import tempfile

    from superfarm.config import Config
    from superfarm.host import capacity
    from superfarm.host.gpu import GpuInfo
    from superfarm.paths import get_paths

    gpus = [GpuInfo(g["node"], g["driver"], g["vendor"], g["name"], g["pci"], list(g["usable_modes"]), g["discrete"], g["vram_mb"]) for g in HOST["gpus"]]
    out = {}
    with tempfile.TemporaryDirectory() as tmp:
        proc = Path(tmp) / "proc"
        proc.mkdir()
        kb = HOST["host"]["ram_mb"] * 1024
        (proc / "meminfo").write_text(f"MemTotal: {kb} kB\nMemFree: {kb - 4 * 1024 * 1024} kB\nMemAvailable: {kb - 3 * 1024 * 1024} kB\n"
                                      f"SwapTotal: {HOST['host']['swap_mb'] * 1024} kB\nHugePages_Total: 0\n")
        (proc / "swaps").write_text("Filename\tType\tSize\tUsed\tPriority\n/swap.img file 16777212 0 -1\n")
        for mode in GPU_MODES:
            config = Config.model_validate({"gpu": {"mode": mode}})
            try:
                out[mode] = capacity.estimate(config, gpus, root=tmp, cpu_threads=HOST["host"]["cpu"]["threads"],
                                              runtime={"ready": True, "icd": True, "missing": []}, paths=get_paths(HOST["home"]))
            except ValueError as e:
                out[mode] = {"error": str(e)}
    return out


def build() -> dict[str, object]:
    sys.path.insert(0, str(ROOT))
    from superfarm import __version__
    from superfarm.ai.tools import all_tools, get_tool
    from superfarm.automation import flows as flows_mod
    from superfarm.config import API_IMMUTABLE_KEYS, Config
    from superfarm.core.models import InstanceSpec

    config = Config()
    examples = []
    for path in sorted(flows_mod.EXAMPLES_DIR.glob("*.yaml")):
        name = f"examples/{path.stem}"
        text = path.read_text(encoding="utf-8")
        flow = flows_mod.parse_flow_text(text, name=name, builtin=True,
                                         forbidden_words=config.automation.forbidden_field_words)
        examples.append({"name": name, "text": text, "summary": flow.summary()})

    approvals = []
    for name, arguments in APPROVAL_SAMPLES:
        tool = get_tool(name)
        checked = tool.validate(dict(arguments))
        approvals.append({"tool": tool.name, "klass": tool.klass, "can_remember": tool.can_remember,
                          "arguments": checked, "one": tool.summary(checked, [901]),
                          "two": tool.summary(checked, [901, 902])})

    return {
        "schema": Config.model_json_schema(),
        "config": {"defaults": config.model_dump(mode="json"), "immutable": list(API_IMMUTABLE_KEYS)},
        "tools": [{"name": t.name, "title": t.title, "class": t.klass, "description": t.description}
                  for t in all_tools()],
        "flows": {"actions": list(flows_mod._KINDS), "examples": examples},      # noqa: SLF001 - the step names
        "approvals": approvals,
        "host": HOST,
        "capacity": demo_capacity(),
        "meta": {"version": __version__, "spec": InstanceSpec(id=1).model_dump(mode="json", exclude={"id", "created"})},
    }


def render(value: object) -> str:
    return HEADER + "export default " + json.dumps(value, indent=1, ensure_ascii=False) + ";\n"


def main(argv: list[str]) -> int:
    check = "--check" in argv
    stale = []
    for name, value in build().items():
        path = OUT / f"{name}.js"
        text = render(value)
        if check:
            if not path.is_file() or path.read_text(encoding="utf-8") != text:
                stale.append(path.relative_to(ROOT).as_posix())
        else:
            OUT.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
    if stale:
        print("out of date: " + ", ".join(stale) + "\nrun: .venv/bin/python demo/scripts/generate.py")
        return 1
    print(f"{'checked' if check else 'wrote'} {len(build())} files in {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
